// One shared "which region is selected" channel for the results page.
//
// Three widgets show the same 432 regions — the SVG brain map, the 3D
// surface viewer, and the region explorer list — and before this they each
// tracked selection privately, so clicking a region in one left the other
// two pointing somewhere else. A CustomEvent on `document` is enough: no
// framework, no store, and any widget added later just subscribes.
//
// `source` lets a widget ignore the echo of its own selection rather than
// re-render (and re-scroll) itself on every click.

const SELECT_EVENT = "region:select";
const HOVER_EVENT = "region:hover";

export function selectRegion(label, source) {
  document.dispatchEvent(new CustomEvent(SELECT_EVENT, { detail: { label, source } }));
}

export function onRegionSelect(handler) {
  document.addEventListener(SELECT_EVENT, (event) => handler(event.detail));
}

export function hoverRegion(label, source) {
  document.dispatchEvent(new CustomEvent(HOVER_EVENT, { detail: { label, source } }));
}

export function onRegionHover(handler) {
  document.addEventListener(HOVER_EVENT, (event) => handler(event.detail));
}

// Shared loader so the three widgets fetch region_names.json once between
// them (generated by scripts/build_region_names.py).
let namesPromise = null;
export function loadRegionNames() {
  if (!namesPromise) {
    namesPromise = fetch("/static/atlas/region_names.json").then((r) => r.json());
  }
  return namesPromise;
}
